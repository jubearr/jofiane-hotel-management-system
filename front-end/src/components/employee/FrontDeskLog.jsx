import React, { useState, useEffect } from 'react';
import { authFetch, readError } from '../../utils/api';
import { todayISO, shiftISODate } from '../../utils/dateUtils';
import { Input, Select, Textarea, ValidatedForm, SubmitButton } from '../common/FormControls';
import { CardsSkeleton } from '../common/SkeletonLoader';

function FrontDeskLog({ employee = null }) {
  // Logged-in agent's identity for attributing new entries / comments.
  const currentName = employee?.name || 'Staff';
  const currentStaffId = employee?.employee_id || 'STAFF';

  const [selectedDate, setSelectedDate] = useState(todayISO());
  const [selectedShift, setSelectedShift] = useState('all');
  const [searchQuery, setSearchQuery] = useState('');
  const [filterCategory, setFilterCategory] = useState('All');
  const [filterPriority, setFilterPriority] = useState('All');
  const [filterStatus, setFilterStatus] = useState('Open');
  const [showAutoGenerated, setShowAutoGenerated] = useState(true);
  const [showResolved, setShowResolved] = useState(false);
  const [newEntryModal, setNewEntryModal] = useState(false);

  const [entries, setEntries] = useState([]);
  const [isLoading, setIsLoading] = useState(true);
  const [error, setError] = useState(null);

  useEffect(() => {
    const fetchLogs = async () => {
      setIsLoading(true);
      setError(null);
      try {
        const res = await authFetch(`/api/front-desk-logs?date=${selectedDate}`);
        if (!res.ok) throw new Error(`Server error: ${res.status}`);
        const data = await res.json();

        // Each doc: audit_id, datetime, action_type, description, user_id, status
        // We stored full entry JSON in description when creating
        const normalized = data.map(doc => {
          let parsed = {};
          try { parsed = JSON.parse(doc.description); } catch (_) {}
          return {
            id:       doc._id,
            _dbId:    doc._id,
            createdAt: doc.datetime
              ? new Date(doc.datetime.replace(' ', 'T')).toISOString()
              : doc.createdAt,
            createdBy: { staffId: parsed.staffId || 'STAFF', name: doc.user_id || 'Staff' },
            shift:     parsed.shift || 'morning',
            category:  doc.action_type || 'General Note',
            priority:  parsed.priority || 'low',
            status:    (doc.status || 'OPEN').toLowerCase() === 'balanced' ? 'resolved' : 'open',
            pinned:    parsed.pinned || false,
            title:     parsed.title || doc.action_type || '',
            description: parsed.body || '',
            linked:    parsed.linked || null,
            readBy:    parsed.readBy || [],
            comments:  parsed.comments || [],
            isSystemGenerated: parsed.isSystemGenerated || false,
          };
        });

        setEntries(normalized);
      } catch (err) {
        setError('Failed to fetch log entries from server.');
      } finally {
        setIsLoading(false);
      }
    };
    fetchLogs();
  }, [selectedDate]);

  const filteredEntries = entries.filter((entry) => {
    if (selectedShift !== 'all' && entry.shift !== selectedShift) return false;
    if (filterCategory !== 'All' && entry.category !== filterCategory) return false;
    if (filterPriority !== 'All' && entry.priority !== filterPriority) return false;
    if (filterStatus === 'Open' && entry.status !== 'open') return false;
    if (filterStatus === 'Resolved' && entry.status !== 'resolved') return false;
    if (!showAutoGenerated && entry.isSystemGenerated) return false;
    if (!showResolved && entry.status === 'resolved') return false;
    if (searchQuery) {
      const q = searchQuery.toLowerCase();
      return (
        entry.title.toLowerCase().includes(q) ||
        entry.description.toLowerCase().includes(q) ||
        entry.createdBy.name.toLowerCase().includes(q) ||
        (entry.linked?.guestName?.toLowerCase().includes(q))
      );
    }
    return true;
  });

  const pinnedEntries = filteredEntries.filter((e) => e.pinned);
  const unpinnedEntries = filteredEntries.filter((e) => !e.pinned);

  const togglePin = (id) => {
    setEntries((prev) =>
      prev.map((e) => (e.id === id ? { ...e, pinned: !e.pinned } : e))
    );
  };

  const deleteEntry = async (id) => {
    const entry = entries.find(e => e.id === id);
    if (entry?._dbId) {
      try {
        const response = await authFetch(`/api/front-desk-logs/${entry._dbId}`, { method: 'DELETE' });
        if (!response.ok) throw new Error(await readError(response, 'Unable to archive this log.'));
        setEntries(prev => prev.filter(e => e.id !== id));
      } catch (e) {
        setError(e.message || 'Unable to archive this log. The entry has been kept.');
      }
    } else setError('This entry has not been saved to the database and cannot be archived.');
  };

  const addComment = (id, commentText) => {
    if (!commentText.trim()) return;
    setEntries((prev) =>
      prev.map((e) =>
        e.id === id
          ? {
              ...e,
              comments: [
                ...e.comments,
                {
                  staffId: currentStaffId,
                  name: currentName,
                  text: commentText,
                  timestamp: new Date().toISOString(),
                },
              ],
            }
          : e
      )
    );
  };

  const [newEntry, setNewEntry] = useState({
    title: '',
    description: '',
    category: 'General Note',
    priority: 'low',
    linkedGuest: '',
    linkedRoom: '',
    pin: false,
  });

  const handleCreateEntry = async () => {
    if (!newEntry.title.trim()) { alert('Please enter a title.'); return; }

    // Store full entry as JSON in description; action_type = category
    const payload = {
      action_type: newEntry.category,
      user_id:     currentName,   // the logged-in front-desk agent
      status:      'OPEN',
      description: JSON.stringify({
        title:    newEntry.title,
        body:     newEntry.description,
        category: newEntry.category,
        priority: newEntry.priority,
        shift:    'morning',
        pinned:   newEntry.pin,
        linked:   newEntry.linkedGuest
          ? { guestName: newEntry.linkedGuest, roomNumber: parseInt(newEntry.linkedRoom) || null, bookingId: null }
          : null,
        readBy:           [],
        comments:         [],
        isSystemGenerated: false,
        staffId:          currentStaffId,
      }),
    };

    try {
      const res = await authFetch('/api/front-desk-logs', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify(payload),
      });
      if (!res.ok) throw new Error(`Server error: ${res.status}`);
      const saved = await res.json();

      // Add optimistically to the UI without a full refetch
      const entry = {
        id:       saved._id,
        _dbId:    saved._id,
        createdAt: new Date().toISOString(),
        createdBy: { staffId: currentStaffId, name: currentName },
        shift:    'morning',
        category: newEntry.category,
        priority: newEntry.priority,
        status:   'open',
        pinned:   newEntry.pin,
        title:    newEntry.title,
        description: newEntry.description,
        linked:   newEntry.linkedGuest
          ? { guestName: newEntry.linkedGuest, roomNumber: parseInt(newEntry.linkedRoom) || null, bookingId: null }
          : null,
        readBy:   [],
        comments: [],
        isSystemGenerated: false,
      };
      setEntries(prev => [entry, ...prev]);
    } catch (e) {
      console.error(e);
      alert('Failed to save log entry. Please try again.');
    }

    setNewEntryModal(false);
    setNewEntry({ title: '', description: '', category: 'General Note', priority: 'low', linkedGuest: '', linkedRoom: '', pin: false });
  };

  return (
    <section className="admin-tab-content active employee-module logbook-module">

      {/* PAGE HEADER */}
      <div className="page-header employee-page-header logbook-header" style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'flex-start', marginBottom: '28px' }}>
        <div>
          <h2 style={{ margin: '0 0 4px 0', fontSize: '30px', fontWeight: '700', color: '#1f2937' }}>Front Desk Logbook</h2>
          <p style={{ margin: 0, fontSize: '14px', color: '#6b7280' }}>Track shift handovers, incidents, maintenance requests, and daily notes.</p>
        </div>
        <div className="employee-page-actions logbook-actions" style={{ display: 'flex', gap: '10px', alignItems: 'center' }}>
          <div className="date-navigator" style={{ display: 'flex', alignItems: 'center' }}>
            <button type="button" aria-label="Previous day" onClick={() => setSelectedDate(prev => shiftISODate(prev, -1))}>
              <svg width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round"><polyline points="15 18 9 12 15 6"></polyline></svg>
            </button>
            <Input type="date" value={selectedDate} onChange={e => setSelectedDate(e.target.value)} />
            <button type="button" aria-label="Next day" onClick={() => setSelectedDate(prev => shiftISODate(prev, 1))}>
              <svg width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round"><polyline points="9 18 15 12 9 6"></polyline></svg>
            </button>
          </div>
          <button className="btn btn-sm btn-gold" onClick={() => setSelectedDate(todayISO())} style={{ borderRadius: '6px', padding: '8px 14px', fontSize: '13px' }}>Today</button>
          <Select value={selectedShift} onChange={e => setSelectedShift(e.target.value)} style={{ padding: '8px 12px', fontSize: '13px', borderRadius: '6px', border: '1px solid #d1d5db', outline: 'none', color: '#374151', background: '#fff' }}>
            <option value="all">All Shifts</option>
            <option value="morning">Morning (7am-3pm)</option>
            <option value="afternoon">Afternoon (3pm-11pm)</option>
            <option value="night">Night (11pm-7am)</option>
          </Select>
          <button onClick={() => setNewEntryModal(true)} className="btn btn-gold" style={{ borderRadius: '6px', padding: '8px 18px', border: 'none', fontWeight: '600', fontSize: '13px', display: 'flex', alignItems: 'center', gap: '6px' }}>
            <i className="fas fa-plus"></i> New Entry
          </button>
        </div>
      </div>

      {/* KPI METRICS */}
      <div className="logbook-kpi-grid" style={{ display: 'grid', gridTemplateColumns: 'repeat(2, 1fr)', gap: '16px', marginBottom: '28px' }}>

        {/* Open Issues */}
        <div className="kpi-card logbook-kpi-card" style={{ borderRadius: '12px', padding: '24px', background: '#fff', border: '1px solid #e5e7eb', boxShadow: '0 2px 8px rgba(0,0,0,0.04)' }}>
          <div style={{ fontSize: '11px', fontWeight: '700', color: '#78716c', textTransform: 'uppercase', letterSpacing: '1px', marginBottom: '12px' }}>Pending / Open</div>
          <div style={{ fontSize: '40px', fontWeight: '700', color: '#1a1a1a', marginBottom: '10px', lineHeight: '1' }}>{isLoading ? '--' : filteredEntries.filter(e => e.status === 'open').length}</div>
          <div style={{ fontSize: '13px', fontWeight: '500', color: '#dc2626' }}>Requires Attention</div>
        </div>

        {/* Resolved */}
        <div className="kpi-card logbook-kpi-card" style={{ borderRadius: '12px', padding: '24px', background: '#fff', border: '1px solid #e5e7eb', boxShadow: '0 2px 8px rgba(0,0,0,0.04)' }}>
          <div style={{ fontSize: '11px', fontWeight: '700', color: '#78716c', textTransform: 'uppercase', letterSpacing: '1px', marginBottom: '12px' }}>Resolved</div>
          <div style={{ fontSize: '40px', fontWeight: '700', color: '#1a1a1a', marginBottom: '10px', lineHeight: '1' }}>{isLoading ? '--' : filteredEntries.filter(e => e.status === 'resolved').length}</div>
          <div style={{ fontSize: '13px', fontWeight: '500', color: '#059669' }}>Completed</div>
        </div>

      </div>

      {/* MAIN LOG PANEL */}
      <div className="panel logbook-panel" style={{ borderRadius: '10px', border: '1px solid #e5e7eb', padding: '24px', background: '#fff', boxShadow: '0 1px 2px rgba(0,0,0,0.04)' }}>

        {/* Filters Bar */}
        <div className="logbook-filter-bar" style={{ display: 'flex', flexWrap: 'wrap', gap: '12px', alignItems: 'center', marginBottom: '24px', paddingBottom: '20px', borderBottom: '1px solid #f3f4f6' }}>
          <div style={{ position: 'relative', flex: 1, minWidth: '220px' }}>
            <i className="fas fa-search" style={{ position: 'absolute', left: '12px', top: '50%', transform: 'translateY(-50%)', color: '#9ca3af', fontSize: '13px' }}></i>
            <Input type="text" placeholder="Search entries..." value={searchQuery} onChange={e => setSearchQuery(e.target.value)} style={{ width: '100%', padding: '9px 12px 9px 34px', fontSize: '13px', borderRadius: '6px', border: '1px solid #e5e7eb', outline: 'none', color: '#374151', background: '#f9fafb' }} />
          </div>

          <Select value={filterCategory} onChange={e => setFilterCategory(e.target.value)} style={{ padding: '9px 12px', fontSize: '13px', borderRadius: '6px', border: '1px solid #e5e7eb', outline: 'none', color: '#374151', background: '#fff' }}>
            <option value="All">All Categories</option>
            <option value="General Note">General Note</option>
            <option value="Guest Request">Guest Request</option>
            <option value="Incident">Incident</option>
            <option value="Maintenance">Maintenance</option>
            <option value="VIP Note">VIP Note</option>
            <option value="Shift Summary">Shift Summary</option>
          </Select>

          <Select value={filterPriority} onChange={e => setFilterPriority(e.target.value)} style={{ padding: '9px 12px', fontSize: '13px', borderRadius: '6px', border: '1px solid #e5e7eb', outline: 'none', color: '#374151', background: '#fff' }}>
            <option value="All">All Priorities</option>
            <option value="high">High</option>
            <option value="medium">Medium</option>
            <option value="low">Low</option>
          </Select>

          <Select value={filterStatus} onChange={e => setFilterStatus(e.target.value)} style={{ padding: '9px 12px', fontSize: '13px', borderRadius: '6px', border: '1px solid #e5e7eb', outline: 'none', color: '#374151', background: '#fff' }}>
            <option value="Open">Open</option>
            <option value="Resolved">Resolved</option>
            <option value="All">All Status</option>
          </Select>

          <label style={{ display: 'flex', alignItems: 'center', gap: '6px', fontSize: '13px', color: '#4b5563', cursor: 'pointer', whiteSpace: 'nowrap' }}>
            <Input type="checkbox" checked={showAutoGenerated} onChange={e => setShowAutoGenerated(e.target.checked)} style={{ accentColor: '#b8860b' }} /> System
          </label>
          <label style={{ display: 'flex', alignItems: 'center', gap: '6px', fontSize: '13px', color: '#4b5563', cursor: 'pointer', whiteSpace: 'nowrap' }}>
            <Input type="checkbox" checked={showResolved} onChange={e => setShowResolved(e.target.checked)} style={{ accentColor: '#b8860b' }} /> Resolved
          </label>
        </div>

        {error && <div style={{ color: '#dc2626', fontSize: '13px', marginBottom: '16px', padding: '10px 14px', background: '#fef2f2', borderRadius: '6px', border: '1px solid #fecaca' }}>{error}</div>}

        {/* Log Feed */}
        <div className="logbook-feed" style={{ display: 'flex', flexDirection: 'column', gap: '14px' }}>
          {isLoading ? (
            <CardsSkeleton cards={3} label="Loading front desk log" />
          ) : (
            <>
              {pinnedEntries.length > 0 && (
                <div>
                  <div style={{ fontSize: '11px', fontWeight: '700', color: '#6b7280', textTransform: 'uppercase', marginBottom: '10px', letterSpacing: '0.6px', display: 'flex', alignItems: 'center', gap: '6px' }}>
                    <i className="fas fa-thumbtack" style={{ fontSize: '10px' }}></i> Pinned Entries
                  </div>
                  <div style={{ display: 'flex', flexDirection: 'column', gap: '10px' }}>
                    {pinnedEntries.map((entry) => (
                      <LogEntryCard key={entry.id} entry={entry} onTogglePin={togglePin} onDelete={deleteEntry} onAddComment={addComment} />
                    ))}
                  </div>
                </div>
              )}

              <div>
                {pinnedEntries.length > 0 && (
                  <div style={{ fontSize: '11px', fontWeight: '700', color: '#6b7280', textTransform: 'uppercase', marginBottom: '10px', marginTop: '14px', letterSpacing: '0.6px' }}>All Entries</div>
                )}
                <div style={{ display: 'flex', flexDirection: 'column', gap: '10px' }}>
                  {unpinnedEntries.map((entry) => (
                    <LogEntryCard key={entry.id} entry={entry} onTogglePin={togglePin} onDelete={deleteEntry} onAddComment={addComment} />
                  ))}
                </div>
              </div>

              {filteredEntries.length === 0 && (
                <div style={{ textAlign: 'center', padding: '48px 20px', color: '#9ca3af' }}>
                  <i className="fas fa-inbox" style={{ fontSize: '24px', display: 'block', marginBottom: '10px' }}></i>
                  No log entries match the current filters.
                </div>
              )}
            </>
          )}
        </div>
      </div>

      {/* New Entry Modal */}
      {newEntryModal && (
        <div className="modal-overlay logbook-modal-overlay open" style={{ position: 'fixed', top: 0, left: 0, right: 0, bottom: 0, display: 'flex', alignItems: 'center', justifyContent: 'center', zIndex: 1000 }}>
          <div className="modal-content logbook-modal logbook-new-entry" style={{ width: 480, maxWidth: '92%', padding: '28px', borderRadius: '12px', boxShadow: '0 20px 60px rgba(0,0,0,0.15)' }}>
            <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center', marginBottom: '20px' }}>
              <h3 style={{ margin: 0, fontSize: '18px', fontWeight: '700', color: '#1f2937' }}>New Log Entry</h3>
              <button onClick={() => setNewEntryModal(false)} style={{ background: 'none', border: 'none', cursor: 'pointer', fontSize: '18px', color: '#9ca3af', padding: '4px' }}>
                <i className="fas fa-times"></i>
              </button>
            </div>

            <ValidatedForm className="log-entry-form" onSubmit={(event) => { event.preventDefault(); handleCreateEntry(); }}><div style={{ display: 'flex', flexDirection: 'column', gap: '14px' }}>
              <div style={{ display: 'flex', gap: '12px' }}>
                <div style={{ flex: 1 }}>
                  <label style={{ display: 'block', fontSize: '12px', fontWeight: '600', color: '#374151', marginBottom: '5px' }}>Category</label>
                  <Select value={newEntry.category} onChange={e => setNewEntry({ ...newEntry, category: e.target.value })} style={{ width: '100%', padding: '9px 12px', borderRadius: '6px', border: '1px solid #e5e7eb', outline: 'none', fontSize: '13px', color: '#374151' }}>
                    <option>General Note</option>
                    <option>Guest Request</option>
                    <option>Incident</option>
                    <option>Maintenance</option>
                    <option>VIP Note</option>
                    <option>Shift Summary</option>
                  </Select>
                </div>
                <div style={{ flex: 1 }}>
                  <label style={{ display: 'block', fontSize: '12px', fontWeight: '600', color: '#374151', marginBottom: '5px' }}>Priority</label>
                  <Select value={newEntry.priority} onChange={e => setNewEntry({ ...newEntry, priority: e.target.value })} style={{ width: '100%', padding: '9px 12px', borderRadius: '6px', border: '1px solid #e5e7eb', outline: 'none', fontSize: '13px', color: '#374151' }}>
                    <option value="low">Low</option>
                    <option value="medium">Medium</option>
                    <option value="high">High</option>
                  </Select>
                </div>
              </div>

              <div>
                <label style={{ display: 'block', fontSize: '12px', fontWeight: '600', color: '#374151', marginBottom: '5px' }}>Title</label>
                <Input type="text" value={newEntry.title} required onChange={e => setNewEntry({ ...newEntry, title: e.target.value })} style={{ width: '100%', padding: '9px 12px', borderRadius: '6px', border: '1px solid #e5e7eb', outline: 'none', fontSize: '13px', color: '#374151' }} placeholder="Brief summary..." />
              </div>

              <div>
                <label style={{ display: 'block', fontSize: '12px', fontWeight: '600', color: '#374151', marginBottom: '5px' }}>Description</label>
                <Textarea value={newEntry.description} required onChange={e => setNewEntry({ ...newEntry, description: e.target.value })} rows={3} style={{ width: '100%', padding: '9px 12px', borderRadius: '6px', border: '1px solid #e5e7eb', outline: 'none', fontSize: '13px', color: '#374151', resize: 'vertical' }} placeholder="Full details..." />
              </div>

              <div style={{ display: 'flex', gap: '12px' }}>
                <div style={{ flex: 1 }}>
                  <label style={{ display: 'block', fontSize: '12px', fontWeight: '600', color: '#374151', marginBottom: '5px' }}>Guest (optional)</label>
                  <Input type="text" value={newEntry.linkedGuest} onChange={e => setNewEntry({ ...newEntry, linkedGuest: e.target.value })} style={{ width: '100%', padding: '9px 12px', borderRadius: '6px', border: '1px solid #e5e7eb', outline: 'none', fontSize: '13px', color: '#374151' }} placeholder="Guest name" />
                </div>
                <div style={{ width: '100px' }}>
                  <label style={{ display: 'block', fontSize: '12px', fontWeight: '600', color: '#374151', marginBottom: '5px' }}>Room</label>
                  <Input type="number" value={newEntry.linkedRoom} onChange={e => setNewEntry({ ...newEntry, linkedRoom: e.target.value })} style={{ width: '100%', padding: '9px 12px', borderRadius: '6px', border: '1px solid #e5e7eb', outline: 'none', fontSize: '13px', color: '#374151' }} placeholder="#" />
                </div>
              </div>

              <label style={{ display: 'flex', alignItems: 'center', gap: '8px', fontSize: '13px', color: '#374151', cursor: 'pointer' }}>
                <Input type="checkbox" checked={newEntry.pin} onChange={e => setNewEntry({ ...newEntry, pin: e.target.checked })} style={{ accentColor: '#b8860b' }} />
                Pin this entry to the top
              </label>
            </div>

            <div style={{ marginTop: '22px', display: 'flex', justifyContent: 'flex-end', gap: '10px', paddingTop: '16px', borderTop: '1px solid #f3f4f6' }}>
              <button onClick={() => setNewEntryModal(false)} style={{ padding: '9px 18px', background: '#f3f4f6', border: 'none', borderRadius: '6px', color: '#4b5563', fontSize: '13px', fontWeight: '500', cursor: 'pointer' }}>Cancel</button>
              <SubmitButton className="btn btn-gold" style={{ padding: '9px 18px', border: 'none', borderRadius: '6px', fontSize: '13px', fontWeight: '600', cursor: 'pointer' }}>Create Entry</SubmitButton>
            </div>
            </ValidatedForm>
          </div>
        </div>
      )}
    </section>
  );
}

/* Sub-component for a single log entry card */
function LogEntryCard({ entry, onTogglePin, onDelete, onAddComment }) {
  const [commentText, setCommentText] = useState('');
  const [showComments, setShowComments] = useState(false);

  const priorityColors = {
    high: { border: '#dc2626', bg: '#fef2f2', badge: '#dc2626' },
    medium: { border: '#d97706', bg: '#fffbeb', badge: '#d97706' },
    low: { border: '#d1d5db', bg: '#ffffff', badge: '#6b7280' },
  };

  const colors = priorityColors[entry.priority];
  const resolvedStyle = entry.status === 'resolved' ? { opacity: 0.55 } : {};

  return (
    <div className="log-entry-card" style={{ borderLeft: `4px solid ${colors.border}`, background: colors.bg, ...resolvedStyle, borderRadius: '8px', padding: '16px 20px', border: `1px solid #e5e7eb`, borderLeftWidth: '4px', borderLeftColor: colors.border, transition: 'box-shadow 0.15s ease' }}>
      <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'flex-start' }}>
        <div style={{ flex: 1, minWidth: 0 }}>
          {/* Meta row */}
          <div className="log-entry-meta" style={{ display: 'flex', alignItems: 'center', gap: '8px', fontSize: '11px', color: '#6b7280', marginBottom: '8px', flexWrap: 'wrap' }}>
            <span style={{ padding: '2px 8px', borderRadius: '4px', fontWeight: '700', fontSize: '10px', textTransform: 'uppercase', letterSpacing: '0.4px', color: '#fff', background: colors.badge }}>
              {entry.priority}
            </span>
            <span style={{ fontWeight: '500' }}>{new Date(entry.createdAt).toLocaleTimeString('en-US', { hour: '2-digit', minute: '2-digit' })}</span>
            <span style={{ color: '#d1d5db' }}>|</span>
            <span style={{ fontWeight: '500' }}>{entry.category}</span>
            {entry.isSystemGenerated && (
              <span className="log-system-badge" style={{ background: '#e5e7eb', color: '#374151', padding: '2px 8px', borderRadius: '4px', fontWeight: '600', fontSize: '10px' }}>SYSTEM</span>
            )}
            {entry.status === 'resolved' && (
              <span style={{ color: '#059669', fontWeight: '600', display: 'flex', alignItems: 'center', gap: '4px' }}>
                <i className="fas fa-check-circle" style={{ fontSize: '11px' }}></i> Resolved
              </span>
            )}
          </div>

          {/* Title */}
          <h4 style={{ margin: '0 0 6px 0', fontSize: '14px', fontWeight: '600', color: '#1f2937', lineHeight: '1.4' }}>{entry.title}</h4>

          {/* Description */}
          <p style={{ margin: 0, fontSize: '13px', color: '#4b5563', whiteSpace: 'pre-line', lineHeight: '1.6' }}>{entry.description}</p>

          {/* Linked info */}
          {entry.linked && (
            <div className="log-linked-info" style={{ display: 'flex', gap: '14px', fontSize: '12px', color: '#0369a1', marginTop: '10px', fontWeight: '500' }}>
              {entry.linked.guestName && (
                <span style={{ display: 'flex', alignItems: 'center', gap: '4px' }}>
                  <i className="fas fa-user" style={{ fontSize: '10px' }}></i> {entry.linked.guestName}
                </span>
              )}
              {entry.linked.roomNumber && (
                <span style={{ display: 'flex', alignItems: 'center', gap: '4px' }}>
                  <i className="fas fa-door-open" style={{ fontSize: '10px' }}></i> Room {entry.linked.roomNumber}
                </span>
              )}
              {entry.linked.bookingId && (
                <span style={{ display: 'flex', alignItems: 'center', gap: '4px' }}>
                  <i className="fas fa-file-alt" style={{ fontSize: '10px' }}></i> {entry.linked.bookingId}
                </span>
              )}
            </div>
          )}

          {/* Footer meta */}
          <div className="log-entry-footer-meta" style={{ marginTop: '12px', fontSize: '11px', color: '#9ca3af', display: 'flex', alignItems: 'center', gap: '10px', flexWrap: 'wrap' }}>
            <span style={{ display: 'flex', alignItems: 'center', gap: '4px' }}>
              <i className="fas fa-user-circle" style={{ fontSize: '12px' }}></i> {entry.createdBy.name}
            </span>
            <span style={{ color: '#e5e7eb' }}>|</span>
            <span style={{ display: 'flex', alignItems: 'center', gap: '4px' }}>
              <i className="fas fa-eye" style={{ fontSize: '10px' }}></i> {entry.readBy.length} read
            </span>
            {entry.comments.length > 0 && (
              <button className="log-comment-toggle" onClick={() => setShowComments(!showComments)} style={{ background: 'none', border: 'none', color: '#2563eb', cursor: 'pointer', padding: 0, fontSize: '11px', fontWeight: '500', display: 'flex', alignItems: 'center', gap: '4px' }}>
                <i className="fas fa-comment" style={{ fontSize: '10px' }}></i> {entry.comments.length} comment{entry.comments.length > 1 ? 's' : ''}
              </button>
            )}
          </div>
        </div>

        {/* Action Buttons */}
        <div className="log-entry-actions" style={{ display: 'flex', flexDirection: 'column', gap: '8px', marginLeft: '16px' }}>
          <button
            onClick={() => onTogglePin(entry.id)}
            title={entry.pinned ? 'Unpin' : 'Pin to top'}
            aria-label={entry.pinned ? 'Unpin entry' : 'Pin entry to top'}
            style={{ background: 'none', border: 'none', cursor: 'pointer', color: entry.pinned ? '#b45309' : '#9ca3af', fontSize: '14px', padding: '4px', transition: 'color 0.15s ease' }}
          >
            <i className="fas fa-thumbtack"></i>
          </button>
          <button
            onClick={() => onDelete(entry.id)}
            title="Delete entry"
            aria-label="Delete entry"
            style={{ background: 'none', border: 'none', cursor: 'pointer', color: '#9ca3af', fontSize: '14px', padding: '4px', transition: 'color 0.15s ease' }}
          >
            <i className="fas fa-trash-alt"></i>
          </button>
        </div>
      </div>

      {/* Comments Section */}
      {showComments && (
        <div style={{ marginTop: '14px', borderTop: '1px solid #f3f4f6', paddingTop: '12px' }}>
          {entry.comments.map((c, idx) => (
            <div key={idx} style={{ fontSize: '12px', color: '#4b5563', marginBottom: '8px', display: 'flex', gap: '8px', alignItems: 'baseline' }}>
              <span style={{ fontWeight: '600', color: '#1f2937', whiteSpace: 'nowrap' }}>{c.name}</span>
              <span style={{ lineHeight: '1.4' }}>{c.text}</span>
              <span style={{ color: '#9ca3af', fontSize: '10px', whiteSpace: 'nowrap', marginLeft: 'auto' }}>{new Date(c.timestamp).toLocaleTimeString('en-US', { hour: '2-digit', minute: '2-digit' })}</span>
            </div>
          ))}
          <div style={{ display: 'flex', gap: '8px', marginTop: '10px' }}>
            <Input
              type="text"
              value={commentText}
              onChange={(e) => setCommentText(e.target.value)}
              onKeyDown={(e) => { if (e.key === 'Enter') { onAddComment(entry.id, commentText); setCommentText(''); } }}
              placeholder="Add a comment..."
              style={{ flex: 1, padding: '7px 12px', borderRadius: '6px', border: '1px solid #e5e7eb', fontSize: '12px', outline: 'none', color: '#374151' }}
            />
            <button onClick={() => { onAddComment(entry.id, commentText); setCommentText(''); }} className="btn btn-gold" style={{ padding: '7px 14px', borderRadius: '6px', fontSize: '12px', border: 'none', fontWeight: '600', cursor: 'pointer' }}>Post</button>
          </div>
        </div>
      )}
    </div>
  );
}

export default FrontDeskLog;
